-- =============================================================
-- 리포트 시각을 서버 기록으로 일원화 (#55 — 매뉴얼 14단계)
--
--  무엇이 문제였나
--    #55 로 services 에 진행 시각 12개를 넣으면서 20260708000032 의
--    머리말에 이렇게 적었다.
--
--      "매뉴얼은 각 단계에서 시각을 기록하라고 요구하고, 그 값이 그대로
--       결과보고(14단계)의 입력이 된다. 파트너가 종이에 적었다가 옮기는
--       대신 앱이 누른 시각을 그대로 남긴다."
--
--    결과보고 쪽이 연결되지 않았다. 파트너는 버튼으로 시각을 남긴 뒤
--    리포트 화면에서 만난 시간·종료 시간을 <input type="time"> 에
--    **손으로 다시 쳤고**, 그 값이 이 두 컬럼에 text 로 들어갔다.
--
--  왜 지우는가
--    ① 매뉴얼 4·13단계·대응카드 26 이 "임의의 시각을 입력하지 않는다" 고
--       규정한다. 손으로 치는 칸이 있는 한 규정은 화면에서 지켜지지 않는다.
--
--    ② 보호자가 보는 시간과 청구되는 시간이 갈린다. 청구는 services 의
--       started_at·ended_at 으로 계산되는데 리포트에는 파트너가 친 값이
--       실린다. 약관 제12조 ④ 는 분쟁 시 두 자료를 "함께 확인" 하라고
--       하는데, 함께 확인하면 서로 다른 상황이었다. **리포트에 적힌 시간과
--       청구된 시간이 다르다는 사실 자체가 분쟁 사유가 된다.**
--
--    ③ 보관해 둘 이유가 없다. services 가 이미 같은 사실을 더 정확하게
--       갖고 있다. 두 곳에 두면 어긋날 수 있고, 어긋나면 어느 쪽이 맞는지
--       판단할 근거가 없다.
--
--    지금 들어 있는 값은 파트너가 손으로 친 값이라 보존 대상이 아니다.
--    services 쪽 기록이 같은 서비스에 대해 그대로 남아 있다.
-- =============================================================

alter table public.reports
  drop column if exists meet_time,
  drop column if exists end_time;

comment on table public.reports is
  '보호자 리포트. 완료된 서비스 1건당 1행. 수행 시각은 이 테이블에 두지 않는다 — services 의 기록을 그대로 읽어 보여준다(#55, 매뉴얼 14단계).';
