/**
 * 약관·방침 원문을 담는 자료구조.
 *
 *  ⚠️ **정본은 노션이다.** 이 파일들은 노션 원문을 화면에 옮긴 것이고,
 *     조문을 요약하거나 다듬지 않는다. 개정되면 `/legal-sync` 로 노션에서
 *     다시 받아 데이터만 교체한다 — 렌더러는 건드리지 않는다.
 *
 *  내용을 JSX 가 아니라 데이터로 두는 이유는 두 가지다.
 *   1. 개정 시 바뀌는 곳이 데이터 한 곳뿐이라 diff 가 조문과 1:1 로 읽힌다
 *   2. 약관·방침이 같은 렌더러를 쓰므로 두 페이지의 서식이 어긋나지 않는다
 */

export type LegalBlock =
    /** 문단. 항 번호(①②③)는 텍스트에 그대로 포함한다 */
    | { type: "p"; text: string }
    /** 호 목록(1. 2. 3.). 번호는 렌더러가 붙인다 */
    | { type: "list"; items: string[] }
    /** 표 중간의 소제목 (예: "[단계 1] 매칭 전 — 파트너의 수락 여부 검토 단계") */
    | { type: "subhead"; text: string }
    /** 표. 첫 행은 머리행이다 */
    | { type: "table"; head: string[]; rows: string[][] };

export type LegalArticle = {
    /** "제1조" · "부칙" 등 조 번호. 목차 앵커(id)로도 쓰인다 */
    no: string;
    /** "목적" 등 조 제목. 부칙처럼 제목이 없으면 생략한다 */
    title?: string;
    blocks: LegalBlock[];
};

export type LegalDocument = {
    /** "이용약관" · "개인정보처리방침" */
    title: string;
    /** "2026년 9월 3일" — 원문 표기를 그대로 쓴다 (화면 표시용) */
    effectiveDate: string;
    /**
     * 개정일 표기 (화면 표시용). 시행일과 같으면 초판이다.
     *
     * 시행일과 나누는 이유 — 2026-09-06 개정이 실제로 **시행일을 올리지 않고
     * 본문만 고쳤다.** 두 날짜가 하나로 묶여 있으면 그런 개정을 표현할 수 없다.
     */
    revisedDate: string;
    /**
     * 동의 이력의 버전 값 (#58). **개정일 ISO** 다.
     *
     * ⚠️ 전에는 시행일 ISO 였다. 그래서 2026-09-06 개정처럼 시행일을 유지한
     *    개정이 들어오자 **본문은 바뀌었는데 버전이 그대로**가 됐다.
     *    개정 전 본문에 동의한 사람과 개정 후에 동의한 사람의 기록이
     *    구분되지 않았고, `unique (user_id, agreement_type, version)` 때문에
     *    재동의 행조차 들어가지 않았다(#105 · #91).
     *
     *    본문이 바뀌면 이 값이 반드시 바뀌어야 한다. 잊는 것을 막기 위해
     *    `lib/legal/versions.ts` 에 버전별 본문 해시를 두고 CI 가 대조한다.
     */
    version: string;
    articles: LegalArticle[];
};
